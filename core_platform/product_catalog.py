_BY_PRODUCT_ID: dict[str, dict[str, Any]] = {}
for _record in list(PLATFORM_PRODUCTS.values()) + list(FLAGSHIP_PRODUCTS.values()):
    if _record.get("stripe_product_id"):
        _BY_PRODUCT_ID[_record["stripe_product_id"]] = _record


def platform_product(platform_id: str) -> dict[str, Any] | None:
    """The purchasable Stripe-backed record for a platform, or None."""
    return PLATFORM_PRODUCTS.get(platform_id)


def ruled_record(platform_id: str) -> dict[str, Any] | None:
    """The ruled-but-not-in-Stripe record for a platform, or None."""
    return RULED_NOT_IN_STRIPE.get(platform_id)


def record_for_product_id(product_id: str) -> dict[str, Any] | None:
    """Any purchasable record (platform or flagship) by Stripe product id."""
    return _BY_PRODUCT_ID.get(product_id)


def resolve_checkout_record(
    *, platform_id: str | None = None, product_id: str | None = None
) -> dict[str, Any] | None:
    """Resolve a checkout request to its catalog record.

    A platform id resolves first to its Stripe-backed product; a
    platform whose price is ruled but whose Stripe product does not
    exist resolves to its RULED_NOT_IN_STRIPE record (purchasable
    False — the caller reports the boundary). A Stripe product id
    resolves to the platform or flagship record that carries it.
    Anything else resolves to None (unknown product).
    """
    if platform_id:
        record = PLATFORM_PRODUCTS.get(platform_id)
        if record is not None:
            return record
        return RULED_NOT_IN_STRIPE.get(platform_id)
    if product_id:
        return _BY_PRODUCT_ID.get(product_id)
    return None


def catalog_summary() -> dict[str, Any]:
    """Honest census of the map: what can be sold today, what cannot."""
    return {
        "platform_products_purchasable": sum(
            1 for r in PLATFORM_PRODUCTS.values() if r["purchasable"]),
        "platform_products_total": len(PLATFORM_PRODUCTS),
        "flagship_products_purchasable": sum(
            1 for r in FLAGSHIP_PRODUCTS.values() if r["purchasable"]),
        "flagship_products_total": len(FLAGSHIP_PRODUCTS),
        "ruled_not_in_stripe": len(RULED_NOT_IN_STRIPE),
        "ruled_price_lines_blocked": sum(
            len(r.get("tiers", ())) for r in RULED_NOT_IN_STRIPE.values()),
    }



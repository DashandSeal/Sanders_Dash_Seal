        part_key = entry['part']
        designation = db.execute(
            'SELECT * FROM'
            ' the_godfather_human_survival_designations'
            ' WHERE part_key = ? AND state = ? ORDER'
            ' BY recorded_at DESC, rowid DESC LIMIT 1',
            (part_key, 'ACTIVE')).fetchone()
        tested = db.execute(
            'SELECT COUNT(*) AS n FROM'
            ' the_godfather_human_survival_tests'
            ' WHERE capability = ? AND outcome = ?',
            (self._hs_capability(part_key),
             'COMPLETED')).fetchone()['n'] > 0

    def record_hs_test(
            self, actor, part_key, phases, outcome,
            detail_ref, *, region=None):
        """Record one end-to-end test of a Human
        Survival part (operator only), in this
        architecture's tests of record under the part's
        capability. A COMPLETED outcome requires all
        six phases of the delivery cycle \u2014 identify,
        arrange, acquire, deliver, verify, replenish.
        The record is labeled TEST everywhere it
        appears: a test never counts as a real delivery,
        never opens or closes a real matter, and is
        incapable of external dispatch."""
        self._geo(region)
        self._require_operator(actor)
        if (not isinstance(part_key, str)
                or not part_key.strip()):
            raise TheGodfatherDenied(
                'The Human Survival part is required')
        self._hs_part_entry(part_key)
        if outcome not in HS_TEST_OUTCOMES:
            raise TheGodfatherDenied(
                'The test outcome must be one of: '
                + ', '.join(HS_TEST_OUTCOMES))
        if (not isinstance(phases, (list, tuple))
                or not phases):
            raise TheGodfatherDenied(
                'The exercised phases of the delivery'
                ' cycle are required')
        phase_list = []
        for phase in phases:
            if phase not in HS_TEST_PHASES:
                raise TheGodfatherDenied(
                    'Each phase must be one of the'
                    ' delivery cycle: '
                    + ', '.join(HS_TEST_PHASES))
            if phase not in phase_list:
                phase_list.append(phase)
        if (outcome == 'COMPLETED'
                and set(phase_list) != set(HS_TEST_PHASES)):
            raise TheGodfatherDenied(
                'A completed end-to-end test exercises'
                ' the complete delivery cycle \u2014'
                ' identify through replenish, all six'
                ' phases')
        if (not isinstance(detail_ref, str)
                or not detail_ref.strip()):
            raise TheGodfatherDenied(
                'A detail reference is required')
        capability = self._hs_capability(part_key)
        now = self._now()
        test_id = (f'the-godfather-hs-test-'
                   f'{uuid.uuid4().hex[:16]}')
        with self._bloodline_connect() as db:
            db.execute('BEGIN IMMEDIATE;')
            try:
                receipt_id = self._record(
                    'THE_GODFATHER_HS_TEST_RECORDED',
                    actor=actor, test_id=test_id,
                    record_kind='TEST',
                    capability=capability,
                    outcome=outcome,
                    phases=list(phase_list))
                db.execute(
                    'INSERT INTO'
                    ' the_godfather_human_survival_tests'
                    ' (test_id, capability, phases, outcome,'
                    ' detail_ref, recorded_by, recorded_at,'
                    ' receipt_id) VALUES'
                    ' (?, ?, ?, ?, ?, ?, ?, ?)',
                    (test_id, capability,
                     json.dumps(phase_list), outcome,
                     detail_ref.strip(), actor, now,
                     receipt_id))
                db.commit()
            except Exception:
                db.rollback()
                raise
            row = db.execute(
                'SELECT * FROM'
                ' the_godfather_human_survival_tests'
                ' WHERE test_id = ?', (test_id,)).fetchone()
        view = self._hs_test_view(row)
        view['part'] = part_key
        return view


from dataclasses import dataclass

from .rtsa_foundation import PlatformIdentity, validate_identity


@dataclass(frozen=True)
class PlatformDefinition:
    """One platform's complete definition of record: who it is, why
    it exists, whom it serves, its six NACI codes, its service suite,
    its public-facing business model, and its ties to the four
    companies. naics_codes is None only where no codes are of record
    (no platform of record stands in that position since the
    Founder's Headquarters ruling of 2026-11-27)."""

    platform_id: str
    name: str
    who: str
    why: str
    serves: str
    naics_codes: tuple = None
    service_suite: tuple = ()
    business_model: str = ''
    company_tie: str = ''
    companies: tuple = ()
    price_of_record: str = ''
    stripe_product: str = ''
    provenance: str = ''

    def to_dict(self):
        return {
            'platform_id': self.platform_id,
            'name': self.name,
            'who': self.who,
            'why': self.why,
            'serves': self.serves,
            'naics_codes': (list(self.naics_codes)
                             if self.naics_codes is not None else None),
            'service_suite': list(self.service_suite),
            'business_model': self.business_model,
            'company_tie': self.company_tie,
            'companies': list(self.companies),
            'price_of_record': self.price_of_record,
            'stripe_product': self.stripe_product,
            'provenance': self.provenance,
        }


